<?php
// tools/validation-messages.php — the framework's validation messages as a JS module.
//
// Laravel's default validation messages live in the framework's
// `lang/en/validation.php` (the app may publish its own copy; that one wins at
// runtime — the build dumps it with the translations). The kernel needs the
// framework's copy as its fallback, so it is generated into
// kernel/validation-messages.data.mjs — the same shape the app's runtime uses.
//
//   php tools/validation-messages.php <app_root>            # print the JSON
//   php tools/validation-messages.php <app_root> --write    # write the module
//
// The gate (tools/gate.mjs) compares the module with the app's vendor file, so
// the messages cannot rot: a Laravel upgrade that changes a wording is caught.

$appRoot = $argv[1] ?? '';
if ($appRoot === '' || !is_dir($appRoot)) {
    fwrite(STDERR, "usage: php tools/validation-messages.php <app_root> [--write]\n");
    exit(2);
}

$file = $appRoot . '/vendor/laravel/framework/src/Illuminate/Translation/lang/en/validation.php';
if (!is_file($file)) {
    fwrite(STDERR, "validation-messages: the framework's validation.php is missing (" . $file . ")\n");
    exit(3);
}

$messages = require $file;
if (!is_array($messages)) {
    fwrite(STDERR, "validation-messages: the framework's validation.php did not return an array\n");
    exit(4);
}

$json = json_encode($messages, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT);
if ($json === false) {
    fwrite(STDERR, "validation-messages: the messages are not JSON-encodable\n");
    exit(5);
}

if (!in_array('--write', $argv, true)) {
    echo $json, "\n";
    exit(0);
}

$module = "// GENERATED by tools/validation-messages.php — do not edit by hand.\n"
    . "//\n"
    . "// Laravel's default validation messages (the framework's lang/en/validation.php).\n"
    . "// The app may publish its own copy; the build dumps it with the translations and\n"
    . "// the runtime prefers it (Laravel's order: the app's file wins).\n"
    . "export const LARAVEL_VALIDATION_MESSAGES = " . $json . ";\n";

$target = dirname(__DIR__) . '/kernel/validation-messages.data.mjs';
file_put_contents($target, $module);
fwrite(STDOUT, "validation-messages: " . count($messages) . " messages written to kernel/validation-messages.data.mjs\n");
