<?php
// tools/timezone-ids.php — PHP's own timezone identifiers as a JS module.
//
// Laravel 13's `timezone` rule is
//   in_array($value, timezone_identifiers_list(constant(DateTimeZone::ALL)), true)
// (ValidatesAttributes::validateTimezone(), :2754-2760) — the rule is a plain
// membership test against PHP's bundled zoneinfo list, and the argument
// (`timezone:all`, `timezone:per_country`...) selects the list.
//
// The edge runtime's `Intl.supportedValuesOf('timeZone')` is NOT that list: it
// names 19 zones PHP does not (the backwards-compatibility aliases
// `Asia/Calcutta`, `America/Buenos_Aires`, ...) and misses 20 PHP has
// (`UTC`, `America/Nuuk`, `Europe/Kyiv`, ...), so the rule's verdict would
// differ for ~40 zones (probed). The kernel therefore ships PHP's list, dumped
// here.
//
//   php tools/timezone-ids.php            # print the JSON
//   php tools/timezone-ids.php --write    # write kernel/timezone-ids.data.mjs
//
// Re-run after a PHP/zoneinfo upgrade (the tzdata version is whatever built the
// PHP that runs this) — the module records the identifier count.
$write = in_array('--write', $argv, true);
$ids = timezone_identifiers_list(DateTimeZone::ALL);
if (!is_array($ids) || $ids === []) {
    fwrite(STDERR, "timezone-ids: timezone_identifiers_list() answered nothing\n");
    exit(3);
}
$json = json_encode($ids, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT);
if ($json === false) {
    fwrite(STDERR, "timezone-ids: the identifiers are not JSON-encodable\n");
    exit(4);
}
$module = "// GENERATED by tools/timezone-ids.php - do not edit by hand.\n"
    . "//\n"
    . "// PHP 8.3's `timezone_identifiers_list(DateTimeZone::ALL)`, the list Laravel 13's\n"
    . "// `timezone` rule tests with a strict `in_array()` (ValidatesAttributes.php:2754-2760).\n"
    . "// The edge runtime's `Intl.supportedValuesOf('timeZone')` is a DIFFERENT list (it\n"
    . "// names the backwards-compatibility aliases PHP dropped and misses `UTC`,\n"
    . "// `America/Nuuk`, `Europe/Kyiv`, ...), so the kernel ships PHP's own list.\n"
    . "// " . count($ids) . " identifiers; re-run after a PHP or tzdata upgrade.\n"
    . "export const PHP_TIMEZONE_IDS = " . $json . ";\n";
if (!$write) {
    echo $module;
    exit(0);
}
$target = __DIR__ . '/../kernel/timezone-ids.data.mjs';
if (file_put_contents($target, $module) === false) {
    fwrite(STDERR, "timezone-ids: cannot write " . $target . "\n");
    exit(5);
}
echo "wrote " . $target . " (" . count($ids) . " identifiers)\n";
