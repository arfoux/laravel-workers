const RE_SING = new RegExp('^(?:' + UNINFLECTED_SINGULAR.join('|') + ')$', 'i');
const RE_PLUR = new RegExp('^(?:' + UNINFLECTED_PLURAL.join('|') + ')$', 'i');

// Doctrine's Substitutions::inflect(): the key is the lowercased word, and a
// capitalized source yields a capitalized target.
function substitute(map, word) {
  const lower = word.toLowerCase();
  if (!Object.prototype.hasOwnProperty.call(map, lower)) return word;
  const to = map[lower];
  return lower[0] !== word[0] ? to.charAt(0).toUpperCase() + to.slice(1) : to;
}

export function inflectSingular(word) {
  const w = String(word);
  if (w === '') return '';
  if (RE_SING.test(w)) return w;
  const irregular = substitute(IRREGULAR_FLIPPED, w);
  if (irregular !== w) return irregular;
  for (const [pat, rep] of SINGULAR_RULES) {
    const re = new RegExp(pat, 'i');
    if (re.test(w)) return w.replace(re, rep);
  }
  return w;
}

export function inflectPlural(word) {
  const w = String(word);
  if (w === '') return '';
  if (RE_PLUR.test(w)) return w;
  const irregular = substitute(IRREGULAR, w);
  if (irregular !== w) return irregular;
  for (const [pat, rep] of PLURAL_RULES) {
    const re = new RegExp(pat, 'i');
    if (re.test(w)) return w.replace(re, rep);
  }
  return w;
}

// Illuminate\Support\Pluralizer::matchCase(): copy the case of the source word
// onto the inflected one (all-lower, all-upper, First, or Every Word).
export function matchCase(value, comparison) {
  const v = String(value);
  const c = String(comparison);
  if (c.toLowerCase() === c) return v.toLowerCase();
  if (c.toUpperCase() === c) return v.toUpperCase();
  if (ucfirst(c) === c) return ucfirst(v);
  if (ucwords(c) === c) return ucwords(v);
  return v;
}
function ucfirst(s) {
  const t = String(s);
  return t ? t.charAt(0).toUpperCase() + t.slice(1) : t;
}
function ucwords(s) {
  return String(s).replace(/(^|\s)([a-z])/g, (all, sp, ch) => sp + ch.toUpperCase());
}

// Illuminate\Support\Str::singular().
export function singular(value) {
  const v = String(value);
  return matchCase(inflectSingular(v), v);
}

// Illuminate\Support\Str::plural(): the count guard, the uncountable list and
// the "ends in a word character" guard come from Pluralizer::plural().
const UNCOUNTABLE = ['recommended', 'related'];
export function plural(value, count = 2) {
  const v = String(value);
  let c = count;
  if (c && typeof c === 'object' && typeof c.length === 'number' && typeof c !== 'string') c = c.length;
  if (Math.abs(Number(c)) === 1) return v;
  if (UNCOUNTABLE.includes(v.toLowerCase())) return v;
  if (!/^(.*)[A-Za-z0-9\u0080-\uFFFF]$/u.test(v)) return v;
  return matchCase(inflectPlural(v), v);
}
export default { singular, plural, inflectSingular, inflectPlural, matchCase };
