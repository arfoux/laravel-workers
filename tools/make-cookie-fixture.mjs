// tools/make-cookie-fixture.mjs — regenerates kernel/tests/fixtures/laravel-1337-cookies.json
// from a tools/http-oracle.php run.
//
// Usage:
//   node tools/make-cookie-fixture.mjs <http-oracle-output.json> <output.json>
//
// The fixture captures real Set-Cookie bytes + decrypted cookie plaintexts from
// a Laravel 13.37 app so kernel/tests/cookies.test.mjs can verify byte parity
// without booting PHP/Laravel.

import fs from 'node:fs';
import { spawnSync } from 'node:child_process';

const [inputPath, outputPath] = process.argv.slice(2);
if (!inputPath || !outputPath) {
  console.error('usage: node tools/make-cookie-fixture.mjs <http-oracle-output.json> <output.json>');
  process.exit(1);
}

const oracle = JSON.parse(fs.readFileSync(inputPath, 'utf8'));
const keyB64 = oracle.key_b64;

function php(items, mode) {
  const res = spawnSync('php', [new URL('./php-crypto-oracle.php', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')], {
    input: JSON.stringify({ key_b64: keyB64, mode, items }),
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  if (res.error) throw res.error;
  if (res.status !== 0) throw new Error(`php exit ${res.status}: ${res.stderr}`);
  const parsed = JSON.parse(res.stdout);
  for (const item of parsed) {
    if (item && typeof item === 'object' && item.error) throw new Error(`oracle error: ${item.error}`);
  }
  return parsed;
}

const byLabelPrefix = (prefix) => {
  const step = oracle.steps.find((s) => String(s.label).startsWith(prefix));
  if (!step) throw new Error(`step ${prefix} not found`);
  return step;
};

const s1 = byLabelPrefix('s1');
const s9 = byLabelPrefix('s9');
const s10 = byLabelPrefix('s10');
const s12 = byLabelPrefix('s12');

const jarNames = Object.keys(s1.jar_after);
const jarPlain = php(Object.values(s1.jar_after), 'decrypt');
const jarPrefix = php(jarNames, 'prefix');

const fixture = {
  note:
    'Generated by tools/make-cookie-fixture.mjs from a real Laravel 13.37 app (PHP 8.3.30, ' +
    'SESSION_DRIVER=cookie, APP_KEY in key_b64). Do not hand-edit the byte strings.',
  key_b64: keyB64,
  session_cookie_name: oracle.session_cookie_name,
  session_lifetime: oracle.session_lifetime,
  s1: {
    status: s1.status,
    set_cookie: s1.set_cookie,
    jar_after: s1.jar_after,
    jar_plain: Object.fromEntries(jarNames.map((n, i) => [n, jarPlain[i]])),
    jar_prefix: Object.fromEntries(jarNames.map((n, i) => [n, jarPrefix[i]])),
    body: JSON.parse(s1.body),
  },
  s9: {
    status: s9.status,
    set_cookie: s9.set_cookie,
    body: JSON.parse(s9.body),
  },
  s10: {
    status: s10.status,
    set_cookie: s10.set_cookie,
  },
  s12: {
    status: s12.status,
    set_cookie: s12.set_cookie,
    body: JSON.parse(s12.body),
  },
  all_set_cookie: oracle.steps.flatMap((s) => s.set_cookie),
};

fs.mkdirSync(new URL('../kernel/tests/fixtures/', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'), { recursive: true });
fs.writeFileSync(outputPath, JSON.stringify(fixture, null, 1));
console.log(`wrote ${outputPath} (${JSON.stringify(fixture).length} bytes)`);
