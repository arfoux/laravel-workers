// tools/generated.mjs — the marker every generated module in `dist/` starts with.
//
// Seven writers stamp it into the source they emit: build.mjs (runtime config,
// schedule, error views, error renderer, routes), tools/ports.mjs (the guard
// import table) and tools/order-json.mjs (the ordered config modules). It is a
// marker, not a comment style - it tells whoever opens the file that this is
// build output and has to be changed upstream, in the app's own source.
// `kernel/tests/worker-entry.test.mjs` asserts the emitted worker entry carries
// it, and that assertion deliberately spells the text out: an oracle that
// imported this constant could not catch the constant changing.
export const GENERATED_BANNER = '// generated by build.mjs — do not edit';

// The compiled app-metadata artifacts (models/policies/classes) are branded with
// the tool rather than the stage, because the compiler emits them both from the
// full build and from `compiler/bin`. The text is kept as it was - changing it
// would change every emitted file for no gain.
export const COMPILED_BANNER = '// generated by laravel-workers — do not edit';
