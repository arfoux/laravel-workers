<?php
// tools/ascii-map.php — Laravel's `Str::ascii()` as a JS module.
//
// `Str::ascii()` is `voku/portable-ascii`'s `ASCII::to_ascii($value)`, and
// `Str::slug()` runs its title through it first. The kernel used to carry a
// hand-written Latin-1 map, so anything past Latin-1 (`ž`, `Ł`, `Œ`, `ß`,
// Greek, Cyrillic) was DROPPED instead of transliterated: `Str::slug('žluťoučký')`
// answered 'lu-ou-k' where Laravel answers 'zlutoucky'.
//
// `to_ascii()` for a language that HAS a map (English does) is only:
//
//   1. `strtr($value, $map)` — the map is
//      `charsArrayWithSingleLanguageValues()`, i.e. `array_merge()` of every
//      language's table, so a repeated key keeps the LAST language's value.
//      The table is where the transliteration actually lives: it merged the
//      Greek, Cyrillic and Latin tables, which is why `Ελληνικά` -> 'ellinika'.
//   2. `remove_unsupported_chars` — the line breaks become spaces, then
//      everything left outside `[\x09\x10\x13\x0A\x0D\x20-\x7E]` is dropped.
//
// `to_transliterate()` (the per-code-point bank tables) is NOT part of that
// path: `to_ascii()` calls it only when the language has no map at all. It
// does not run for 'en', so it is not modelled here.
//
//   php tools/ascii-map.php <app_root>            # print the JSON
//   php tools/ascii-map.php <app_root> --write    # write the module
//
// The gate (tools/gate.mjs -> tools/ascii-map-check.mjs) regenerates and
// compares, so a Laravel upgrade that changes portable-ascii is caught.

require_once __DIR__ . '/_root.php';

$appRoot = $argv[1] ?? '';
if ($appRoot === '' || !is_dir($appRoot)) {
    fwrite(STDERR, "usage: php tools/ascii-map.php <app_root> [--write]\n");
    exit(2);
}

$autoload = lw_vendor_autoload_for($appRoot);
if (!is_file($autoload)) {
    fwrite(STDERR, "ascii-map: no autoloader for " . $appRoot . "\n");
    exit(3);
}
require_once $autoload;

if (!class_exists(\voku\helper\ASCII::class)) {
    fwrite(STDERR, "ascii-map: voku\\helper\\ASCII is not autoloadable for " . $appRoot . "\n");
    exit(4);
}

// The table `to_ascii()` replaces with. `charsArray()` takes no language
// argument, so it is NOT this map: the merged, single-language one is.
$merged = \voku\helper\ASCII::charsArrayWithSingleLanguageValues(false, false);
if (!is_array($merged)) {
    fwrite(STDERR, "ascii-map: charsArrayWithSingleLanguageValues() did not return an array\n");
    exit(5);
}

// Pairs, not a map: `strtr()` prefers the longest key and the table order
// breaks ties, so both have to survive the round trip.
$pairs = [];
foreach ($merged as $key => $value) {
    $pairs[] = [(string) $key, (string) $value];
}

$json = json_encode($pairs, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT);
if ($json === false) {
    fwrite(STDERR, "ascii-map: the table is not JSON-encodable\n");
    exit(5);
}

if (!in_array('--write', $argv, true)) {
    echo $json, "\n";
    exit(0);
}

$module = "// GENERATED by tools/ascii-map.php — do not edit by hand.\n"
    . "//\n"
    . "// `Str::ascii()`'s replacement table: the pairs `strtr()` is given, in\n"
    . "// table order. The kernel replays `strtr()` (longest key first, the table\n"
    . "// order breaking ties) and then strips what is left, exactly as\n"
    . "// `ASCII::to_ascii('en')` does.\n"
    . "export const LARAVEL_ASCII_REPLACE = " . $json . ";\n";

$target = dirname(__DIR__) . '/kernel/ascii-map.data.mjs';
if (file_put_contents($target, $module) === false) {
    fwrite(STDERR, "ascii-map: cannot write {$target}\n");
    exit(1);
}
fwrite(STDOUT, "ascii-map: " . count($pairs) . " replacement pairs written to kernel/ascii-map.data.mjs\n");
